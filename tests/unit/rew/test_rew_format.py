FIXTURE = Path(__file__).parents[2] / "fixtures" / "rew-filters.txt"
REW_TEXT = FIXTURE.read_text()


def block(n: int, bq: Biquad, sep: str = "\n") -> str:
    return sep.join([f"biquad{n},", *(f"{k}={v!r}," for k, v in zip(KEYS, bq.as_tuple(), strict=True))])


def test_fixture_parses_into_ten_stable_filters():
    parsed = parse_rew(REW_TEXT)
    assert parsed.ok and parsed.errors == [] and parsed.warnings == []
    assert [f.number for f in parsed.filters] == list(range(1, 11))
    assert [f.line for f in parsed.filters] == list(range(1, 61, 6))
    first, last = parsed.filters[0].biquad, parsed.filters[-1].biquad
    assert first.as_tuple() == (
        0.999194903557377,
        -1.9973354686174658,
        0.9981886333563846,
        1.9973354686174658,
        -0.9973835369137615,
    )
    assert last.as_tuple() == (
        0.8784231224481471,
        -1.2978927199484762,
        0.7320089079645271,
        1.2978927199484762,
        -0.6104320304126742,
    )
    assert all(bq.is_stable for bq in parsed.biquads)


def test_fixture_matches_minidsp_rs_float32_values():
    # The values minidsp-rs' own test expects after parsing as f32 (formats/rew.rs).
    import numpy as np

    first = np.array(parse_rew(REW_TEXT).biquads[0].as_tuple(), dtype=np.float32)
    expected = np.array([0.9991949, -1.9973354, 0.9981886, 1.9973354, -0.99738353], dtype=np.float32)
    assert (first == expected).all()


def test_export_of_the_parsed_fixture_is_byte_identical():
    assert export_rew(parse_rew(REW_TEXT).biquads) == REW_TEXT


def test_export_layout():
    text = export_rew([PASSTHROUGH, Biquad(b0=0.5, b1=-0.0, b2=1e-07, a1=0.25, a2=-0.125)])
    assert text == (
        "biquad1,\nb0=1.0,\nb1=0.0,\nb2=0.0,\na1=0.0,\na2=0.0,\n"
        "biquad2,\nb0=0.5,\nb1=0.0,\nb2=1e-07,\na1=0.25,\na2=-0.125\n"
    )
    assert export_rew([]) == ""


finite = st.floats(min_value=-4.0, max_value=4.0, allow_nan=False, allow_infinity=False)


@st.composite
def stable_biquads(draw) -> Biquad:
    a2 = draw(st.floats(min_value=-0.999, max_value=0.999))
    a1 = draw(st.floats(min_value=-(1 - a2) * 0.999, max_value=(1 - a2) * 0.999))
    return Biquad(b0=draw(finite), b1=draw(finite), b2=draw(finite), a1=a1, a2=a2)


@given(st.lists(stable_biquads(), min_size=1, max_size=12))
def test_round_trip_is_exact(biquads):
    parsed = parse_rew(export_rew(biquads))
    assert parsed.ok, parsed.errors
    assert [b.as_tuple() for b in parsed.biquads] == [b.as_tuple() for b in biquads]


@given(st.text(max_size=400))
def test_parser_never_raises(text):
    parsed = parse_rew(text)
    assert parsed.ok or parsed.errors


def test_lenient_syntax():
    lp, hp = lowpass2(80, 0.7071), highpass2(20, 0.7071)
    one_line = block(1, lp, sep=" ")
    loose = "\n".join(
        [
            "# exported by hand",
            "BIQUAD2:",
            *(f"  {k.upper()} = {v!r} ,   # {k}" for k, v in zip(KEYS, hp.as_tuple(), strict=True)),
        ]
    )
    text = "\ufeff" + (one_line + "\n\n" + loose).replace("\n", "\r\n")
    parsed = parse_rew(text)
    assert parsed.ok and parsed.warnings == []
    assert parsed.biquads == [lp, hp]
    assert [f.number for f in parsed.filters] == [1, 2]


def test_exponent_notation_and_java_style():
    parsed = parse_rew("biquad1,\nb0=6.8285941982E-6,\nb1=1.3657e-05,\nb2=6.8285941982e-6,\na1=1.99,\na2=-0.9926")
    assert parsed.ok
    assert math.isclose(parsed.biquads[0].b0, 6.8285941982e-6)


def test_filters_are_used_in_file_order_and_odd_numbering_is_reported():
    a, b = peaking(100, 2, -3), peaking(200, 2, -3)
    parsed = parse_rew(block(5, a) + "\n" + block(5, b))
    assert parsed.ok
    assert parsed.biquads == [a, b]
    [warning] = parsed.warnings
    assert "biquad5 appears twice" in warning.message and warning.line == 7


def test_unknown_lines_are_ignored_with_a_warning():
    text = "Filter Settings export\nGenerated by REW\n" + block(1, PASSTHROUGH)
    parsed = parse_rew(text)
    assert parsed.ok and len(parsed.filters) == 1
    assert [w.line for w in parsed.warnings] == [1, 2]
    assert all("ignored" in w.message for w in parsed.warnings)


def errors(text: str) -> list[str]:
    parsed = parse_rew(text)
    assert not parsed.ok
    return [e.message for e in parsed.errors]


def test_missing_and_duplicate_coefficients():
    assert errors("biquad1,\nb0=1,\nb1=0,\nb2=0,\na1=0") == ["biquad1: missing a2"]
    assert errors("biquad1,\nb0=1,\nb0=1,\nb1=0,\nb2=0,\na1=0,\na2=0") == ["biquad1: b0 given twice"]


def test_bad_numbers():
    assert errors("biquad1,\nb0=abc,\nb1=0,\nb2=0,\na1=0,\na2=0") == [
        "biquad1: b0 is not a number: 'abc'",
        "biquad1: missing b0",
    ]
    assert "not a number" in errors("biquad1,\nb0=nan,\nb1=0,\nb2=0,\na1=0,\na2=0")[0]
    assert "not a number" in errors("biquad1,\nb0=inf,\nb1=0,\nb2=0,\na1=0,\na2=0")[0]


def test_value_before_any_header():
    assert errors("b0=1,\nb1=0") == ["b0 before any biquadN line", "b1 before any biquadN line"]


def test_unstable_filters_are_errors():
    [message] = errors(block(3, Biquad(a1=1.5, a2=-0.2)))
    assert message.startswith("biquad3: unstable biquad")
    # Stable in float64 but not once the device rounds it to float32.
    [message] = errors(block(1, Biquad(a1=0.0, a2=-(1 - 1e-10))))
    assert "unstable" in message


def test_float32_overflow_is_an_error():
    [message] = errors(block(1, Biquad(b0=1e39)))
    assert "float32" in message


def test_filter_settings_text_gets_a_hint():
    text = "Filter  1: ON  PK       Fc   50.0 Hz  Gain  -3.0 dB  Q  5.00\nFilter  2: ON  PK  Fc 80 Hz Gain -2 dB Q 4\n"
    [message] = errors(text)
    assert "filter-settings list" in message


def test_empty_file():
    assert errors("") == ["no biquads found (expected biquad1, b0=…, b1=…, b2=…, a1=…, a2=…)"]
    assert parse_rew("# only a comment\n").errors[0].line == 0


def test_too_many_filters():
    text = "\n".join(block(n, PASSTHROUGH) for n in range(1, MAX_FILTERS + 3))
    parsed = parse_rew(text)
    assert not parsed.ok
    assert parsed.errors[-1].message == f"more than {MAX_FILTERS} filters"
    assert len(parsed.filters) == MAX_FILTERS


def test_a_huge_biquad_number_is_a_warning_not_a_crash():
    parsed = parse_rew("biquad" + "1" * 5000 + ",b0=1,b1=0,b2=0,a1=0,a2=0")
    assert not parsed.ok and parsed.filters == []
    assert parsed.warnings[0].message == "not part of a biquad; ignored"
