@pytest.mark.parametrize(
    ("line", "level", "message"),
    [
        ("[2026-10-17T12:00:00Z ERROR minidspd::http] boom", logging.ERROR, "minidspd::http: boom"),
        (
            "[2026-10-17T12:00:00Z WARN  minidspd::device_manager] Device at usb:x is closing (EOF)",
            logging.WARNING,
            "minidspd::device_manager: Device at usb:x is closing (EOF)",
        ),
        ("[2026-10-17T12:00:00Z INFO  minidspd] probing", logging.DEBUG, "minidspd: probing"),
        ("[2026-10-17T12:00:00Z DEBUG minidspd] x", logging.DEBUG, "minidspd: x"),
        ("thread 'main' panicked at src/main.rs:1:1", logging.WARNING, "thread 'main' panicked at src/main.rs:1:1"),
        ("HTTP/TCP listener error: Address in use", logging.WARNING, "HTTP/TCP listener error: Address in use"),
    ],
)
def test_stderr_lines_map_to_log_levels(line, level, message, caplog):
    with caplog.at_level(logging.DEBUG, "minidspd"):
        forward_stderr_line(line)
    assert [(r.levelno, r.getMessage()) for r in caplog.records] == [(level, message)]


def test_blank_stderr_lines_are_dropped(caplog):
    with caplog.at_level(logging.DEBUG, "minidspd"):
        forward_stderr_line("   ")
    assert caplog.records == []


class _Clock:
    def __init__(self) -> None:
        self.t = 1000.0

    def __call__(self) -> float:
        return self.t


def test_repeated_warnings_are_collapsed(caplog):
    clock = _Clock()
    forward = StderrForwarder(repeat_window_s=300, clock=clock)
    line = "[2026-10-17T12:00:00Z WARN  minidspd::device_manager] fail to connect: Access denied"
    with caplog.at_level(logging.INFO, "minidspd"):
        for _ in range(300):  # minidspd's retry loop: one line a second
            forward(line)
            clock.t += 1
        forward(line)
        forward("[2026-10-17T12:00:00Z ERROR minidspd::http] boom")
    assert [(r.levelno, r.getMessage()) for r in caplog.records] == [
        (logging.WARNING, "minidspd::device_manager: fail to connect: Access denied"),
        (
            logging.WARNING,
            "minidspd::device_manager: fail to connect: Access denied (repeated 300 times in the last 300 s)",
        ),
        (logging.ERROR, "minidspd::http: boom"),
    ]


def test_collapsed_repeats_still_reach_debug(caplog):
    forward = StderrForwarder(clock=_Clock())
    with caplog.at_level(logging.DEBUG, "minidspd"):
        forward("HTTP/TCP listener error: Address in use")
        forward("HTTP/TCP listener error: Address in use")
    assert [r.levelno for r in caplog.records] == [logging.WARNING, logging.DEBUG]


def test_forwarder_tracks_a_bounded_number_of_lines(caplog):
    forward = StderrForwarder(max_tracked=2, clock=_Clock())
    with caplog.at_level(logging.INFO, "minidspd"):
        for line in ("a", "b", "c", "a"):  # "a" was evicted, so it is logged again
            forward(line)
    assert [r.getMessage() for r in caplog.records] == ["a", "b", "c", "a"]
