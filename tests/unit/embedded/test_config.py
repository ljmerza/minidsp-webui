def test_default_config_is_loopback_without_tcp_server_or_discovery():
    text = render_config()
    doc = tomllib.loads(text)
    assert doc == {"ignore_advertisements": True, "http_server": {"bind_address": "127.0.0.1:5380"}}
    assert "tcp_server" not in text
    assert text.startswith("# Generated by minidsp-webui")


def test_mock_adds_a_static_mock_device():
    doc = tomllib.loads(render_config(mock=True))
    assert doc["static_device"] == [{"url": f"mock:?serial={MOCK_SERIAL}"}]
    assert 900000 <= MOCK_SERIAL <= 965535  # minidsp-rs refuses other mock serials


def test_discovery_turns_advertisements_back_on():
    assert tomllib.loads(render_config(discovery=True))["ignore_advertisements"] is False


def test_http_bind_is_passed_through():
    doc = tomllib.loads(render_config(http_bind="0.0.0.0:5380"))
    assert doc["http_server"]["bind_address"] == "0.0.0.0:5380"


def test_extra_config_merges_tables_and_appends_arrays():
    extra = """
ignore_advertisements = false

[http_server]
allowed_origins = "*"

[[static_device]]
url = "tcp://wi-dg.example.lan:5333"

[[tcp_server]]
bind_address = "127.0.0.1:5333"
advertise = { ip = "10.0.0.2", name = "Living room" }
"""
    doc = tomllib.loads(render_config(mock=True, extra=extra))
    assert doc["ignore_advertisements"] is False
    assert doc["http_server"] == {"bind_address": "127.0.0.1:5380", "allowed_origins": "*"}
    assert [d["url"] for d in doc["static_device"]] == [
        f"mock:?serial={MOCK_SERIAL}",
        "tcp://wi-dg.example.lan:5333",
    ]
    assert doc["tcp_server"] == [
        {"bind_address": "127.0.0.1:5333", "advertise": {"ip": "10.0.0.2", "name": "Living room"}}
    ]


def test_extra_config_top_level_keys_never_land_inside_a_table():
    # Appending raw text would put this key inside [[static_device]]; merging keeps it top-level.
    doc = tomllib.loads(render_config(mock=True, extra="ignore_advertisements = false"))
    assert doc["ignore_advertisements"] is False
    assert doc["static_device"] == [{"url": f"mock:?serial={MOCK_SERIAL}"}]


@pytest.mark.parametrize(
    ("extra", "message"),
    [
        ("[http_server", "not valid TOML"),
        ('[http_server]\nbind_address = "0.0.0.0:1"', "MINIDSPD_HTTP_BIND"),
        ("http_server = 1", "must be a table"),
        ('http_server = "x"', "must be a table"),
        ('http_server = "bind_address"', "must be a table"),
    ],
)
def test_bad_extra_config_is_refused(extra, message):
    with pytest.raises(EmbeddedConfigError, match=message):
        render_config(extra=extra)


def test_blank_extra_config_is_ignored():
    assert build_config(extra="  \n") == build_config()


