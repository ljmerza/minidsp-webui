# --- config directory -------------------------------------------------------------------------------------------------


def test_preferred_dir_is_used_when_writable(tmp_path):
    path, created = prepare_config_dir(str(tmp_path / "run" / "minidsp"))
    assert path == tmp_path / "run" / "minidsp" and not created
    assert list(path.iterdir()) == []  # the write probe is gone


def test_unwritable_dir_falls_back_to_shm(tmp_path, caplog):
    blocker = tmp_path / "file"
    blocker.write_text("")
    shm = tmp_path / "shm"
    shm.mkdir()
    with caplog.at_level(logging.INFO, "app.daemon.embedded"):
        path, created = prepare_config_dir(str(blocker / "minidsp"), shm=str(shm))
    assert created and path.parent == shm
    assert [r.levelno for r in caplog.records] == [logging.INFO]  # still RAM: not worth a warning


def test_without_shm_falls_back_to_the_temp_dir(tmp_path, caplog):
    blocker = tmp_path / "file"
    blocker.write_text("")
    path, created = prepare_config_dir(str(blocker / "minidsp"), shm=str(tmp_path / "missing"))
    try:
        assert created and path.is_dir()
        assert any(r.levelno == logging.WARNING for r in caplog.records)
    finally:
        path.rmdir()


def test_write_config_replaces_atomically_and_is_private(tmp_path):
    first = write_config("a = 1\n", tmp_path)
    second = write_config("a = 2\n", tmp_path)
    assert first == second == tmp_path / "config.toml"
    assert second.read_text() == "a = 2\n"
    assert stat.S_IMODE(second.stat().st_mode) == 0o600
    assert [p.name for p in tmp_path.iterdir()] == ["config.toml"]


